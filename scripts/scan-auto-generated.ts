import { prisma } from '../api/_prisma.js';

async function scanAutoGenerated() {
  const autoAccounts = await prisma.account.findMany({
    where: {
      description: { contains: 'Auto-generated', mode: 'insensitive' },
      isDeleted: false
    },
    include: {
      parent: true,
      accountType: true,
      journalEntryLines: {
        include: { journalEntry: true }
      },
      openingBalanceLines: true,
      expenseHeads: true,
      revenueHeads: true
    },
    orderBy: { glCode: 'asc' }
  });

  console.log(`Total "Auto-generated" accounts: ${autoAccounts.length}`);
  for (const a of autoAccounts) {
    console.log(`GL: ${a.glCode} | Name: "${a.accountName}" | Parent: ${a.parent?.glCode} (${a.parent?.accountName}) | JE: ${a.journalEntryLines.length} | OB: ${a.openingBalanceLines.length} | ExpHeads: ${a.expenseHeads.length} | RevHeads: ${a.revenueHeads.length}`);
  }

  await prisma.$disconnect();
}

scanAutoGenerated();
